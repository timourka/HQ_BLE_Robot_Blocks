def _g(*rows: str) -> tuple[int, int, int, int, int]:
    """Создать 5x5 glyph из строк вида '01110'."""
    if len(rows) != 5:
        raise ValueError("Glyph must have 5 rows")
    return tuple(int(row, 2) & 0x1F for row in rows)


